"""T10. Independent validator: the 22 production manifests and the new rules, checked with Python.

Validates the manifests with Python jsonschema (Draft 2020-12) and PyYAML against the unchanged
schema/0.1/capability.schema.json, so that the contract does not depend on the Node.js validator.
Then probes the rules added in Phase 1 with manifests that must be rejected, and writes
docs/phase-1-testing/drafts/T10-independent-validator.md.

    python -I research/phase-1/field-audit/crosscheck.py

Exit code 0 when every verdict matches its expectation, 1 otherwise.
"""
import copy
import json
import pathlib
import sys

import yaml
from jsonschema import Draft202012Validator, FormatChecker

ROOT = pathlib.Path(__file__).resolve().parents[3]
SCHEMA = json.loads((ROOT / "schema" / "0.1" / "capability.schema.json").read_text(encoding="utf-8"))
Draft202012Validator.check_schema(SCHEMA)
VALIDATOR = Draft202012Validator(SCHEMA, format_checker=FormatChecker())
CORPUS = sorted((ROOT / "case-studies" / "production-set" / "manifests").rglob("*.capability.yaml"))


def load(path):
    # safe_load reads unquoted dates as date objects (YAML 1.1); the corpus quotes every date and
    # version, as the authoring rules require, so both validators see the same strings.
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def errors(manifest):
    return sorted(VALIDATOR.iter_errors(manifest), key=lambda error: list(error.absolute_path))


rows = []
failures = 0
for path in CORPUS:
    manifest = load(path)
    found = errors(manifest)
    ok = not found
    failures += 0 if ok else 1
    rows.append((manifest.get("id", path.name), "valid", "valid" if ok else f"invalid: {found[0].message[:80]}", ok))

base = load(ROOT / "case-studies" / "production-set" / "manifests" / "chrome-devtools-mcp.capability.yaml")


def probe(label, mutate):
    global failures
    manifest = copy.deepcopy(base)
    mutate(manifest)
    found = errors(manifest)
    ok = bool(found)
    failures += 0 if ok else 1
    where = "/".join(str(part) for part in found[0].absolute_path) if found else "-"
    rows.append((label, "invalid", f"invalid at /{where}" if found else "valid", ok))


probe("publication platformCompatibility holds a language (python)", lambda m: m["publications"][0].update(platformCompatibility=["python"]))
probe("capability-wide platformCompatibility (retired, C14)", lambda m: m.update(platformCompatibility=["claude-code"]))
probe("intendedAudience (retired, C15)", lambda m: m.update(intendedAudience=["developers"]))
probe("integrations token not kebab-case", lambda m: m.update(integrations=["Jira Cloud"]))
probe("unknown top-level field", lambda m: m.update(platforms=["cursor"]))
probe("riskTier missing", lambda m: m.pop("riskTier"))
probe("mcp_server without an mcp interface", lambda m: m.update(interfaces=[{"type": "cli"}]))
probe("assessed riskTier without assessmentReference", lambda m: m.update(riskTier="low"))
probe("impossible date", lambda m: m.update(lastUpdated="2026-02-30"))
probe("setup kind outside the list", lambda m: m["setup"][0].update(kind="secret_file"))
probe("cost model outside the list", lambda m: m["costInformation"].update(model="freemium"))

lines = [
    "# T10. Independent validator (Python)",
    "",
    "| | |",
    "|---|---|",
    "| Date | 2026-11-16 |",
    "| Generated by | `python -I research/phase-1/field-audit/crosscheck.py` (do not edit by hand; rerun instead) |",
    "| Purpose | The 22 production manifests and the Phase 1 rules checked with Python jsonschema (Draft 2020-12), an implementation independent of the Node.js validator. The schema file is used unchanged. |",
    "",
    f"{sum(1 for row in rows if row[3])} of {len(rows)} verdicts match the expectation.",
    "",
    "| Manifest or probe | Expected | Python jsonschema | Match |",
    "|---|---|---|---|",
    *[f"| {label} | {expected} | {got} | {'yes' if ok else '**no**'} |" for label, expected, got, ok in rows],
    "",
]
out = ROOT / "docs" / "phase-1-testing" / "drafts" / "T10-independent-validator.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{sum(1 for row in rows if row[3])}/{len(rows)} verdicts match")
sys.exit(1 if failures else 0)
