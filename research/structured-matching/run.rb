require "digest"
require "json"
require "pathname"
require "yaml"

ROOT = Pathname.new(__dir__).join("../..").expand_path
EXPERIMENT = ROOT.join("research/structured-matching")
VARIANTS = %w[baseline structured augmented].freeze

def read_yaml(path)
  YAML.safe_load(File.read(path, encoding: "UTF-8"))
end

def normalize(text)
  text.downcase.gsub(/[^a-z0-9]+/, " ").strip.gsub(/\s+/, " ")
end

def add_field(fields, key, value)
  return if value.nil?
  raise "Expected text at #{key}" unless value.is_a?(String)
  fields[key] = value unless value.empty?
end

def baseline_fields(metadata)
  fields = {}
  %w[name description].each { |key| add_field(fields, key, metadata[key]) }
  (metadata["keywords"] || []).each_with_index { |value, i| add_field(fields, "keywords/#{i}", value) }
  use_cases = metadata["supportedUseCases"]
  if use_cases.is_a?(String)
    add_field(fields, "supportedUseCases", use_cases)
  else
    (use_cases || []).each_with_index do |use_case, i|
      %w[title description].each { |key| add_field(fields, "supportedUseCases/#{i}/#{key}", use_case[key]) }
    end
  end
  (metadata["interfaces"] || []).each_with_index do |interface, i|
    %w[inputs outputs].each do |direction|
      (interface[direction] || []).each_with_index do |port, j|
        %w[name description mediaType].each { |key| add_field(fields, "interfaces/#{i}/#{direction}/#{j}/#{key}", port[key]) }
      end
    end
  end
  (metadata["embeddedComponents"] || []).each_with_index do |component, i|
    %w[name description].each { |key| add_field(fields, "embeddedComponents/#{i}/#{key}", component[key]) }
  end
  fields
end

def structured_fields(draft)
  fields = {}
  %w[name description].each { |key| add_field(fields, "draft/#{key}", draft.fetch(key)) }
  %w[abilities use_cases].each do |key|
    values = draft.fetch(key)
    raise "Expected nonempty list #{key}" unless values.is_a?(Array) && !values.empty?
    values.each_with_index { |value, i| add_field(fields, "draft/#{key}/#{i}", value) }
  end
  %w[inputs outputs].each do |direction|
    ports = draft.fetch(direction)
    raise "Expected nonempty list #{direction}" unless ports.is_a?(Array) && !ports.empty?
    ports.each_with_index do |port, i|
      %w[name description type media_type].each { |key| add_field(fields, "draft/#{direction}/#{i}/#{key}", port[key]) }
    end
  end
  fields
end

def ratio(numerator, denominator)
  denominator.zero? ? nil : numerator.to_f / denominator
end

def mean(values)
  values = values.compact
  values.empty? ? nil : values.sum / values.length
end

def metrics(ranked, relevant_total)
  relevant = ranked.count { |hit| hit["label"] == "relevant" }
  partial = ranked.count { |hit| hit["label"] == "partial" }
  top = ranked.first(5)
  {
    "retrieved" => ranked.length,
    "relevant_retrieved" => relevant,
    "partial_retrieved" => partial,
    "false_positives" => ranked.length - relevant,
    "relevant_total" => relevant_total,
    "precision" => ratio(relevant, ranked.length),
    "recall" => ratio(relevant, relevant_total),
    "useful_precision" => ratio(relevant + partial, ranked.length),
    "precision_at_5" => ratio(top.count { |hit| hit["label"] == "relevant" }, top.length)
  }
end

def retrieve(items, need, variant)
  items.map do |item|
    evidence = {}
    need.fetch("terms").each do |term|
      phrase = normalize(term)
      matching = item.fetch("fields").fetch(variant).select do |_, value|
        " #{normalize(value)} ".include?(" #{phrase} ")
      end.keys
      evidence[term] = matching unless matching.empty?
    end
    next if evidence.empty?
    label = if need.fetch("relevant").include?(item["id"])
      "relevant"
    elsif need.fetch("partial").include?(item["id"])
      "partial"
    else
      "not_relevant"
    end
    {
      "id" => item["id"], "name" => item["name"], "source_file" => item["source_file"],
      "score" => evidence.length, "label" => label, "matched_terms" => evidence
    }
  end.compact.sort_by { |hit| [-hit["score"], hit["source_file"]] }
end

def pct(value)
  value.nil? ? "N/A" : format("%.1f%%", value * 100)
end

def md(value)
  value.to_s.gsub("|", "\\|").gsub("\n", " ")
end

def report(result)
  lines = [
    "# Structured Discovery Matching Results", "",
    "New local baseline on 16 example records; not a historical Phase 0 result.",
    "Generated by `ruby research/structured-matching/run.rb`. See [method](README.md), [requests and judgments](needs.yaml), and [full results](results.json).", "",
    "## Overall results", "",
    "| Variant | Retrieved pairs | Relevant pairs | Strict precision | Recall | Useful precision | Macro precision | Macro recall |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |"
  ]
  result["summary"].each do |variant, m|
    lines << "| #{variant} | #{m['retrieved']} | #{m['relevant_retrieved']} | #{pct(m['precision'])} | #{pct(m['recall'])} | #{pct(m['useful_precision'])} | #{pct(m['macro_precision'])} | #{pct(m['macro_recall'])} |"
  end
  original_metrics = result["summary"].fetch("baseline")
  draft_metrics = result["summary"].fetch("structured")
  lines.concat(["",
    "Baseline retrieved #{original_metrics['relevant_retrieved']} of #{original_metrics['relevant_total']} relevant request-record pairs in #{original_metrics['retrieved']} results. Structured-only retrieved #{draft_metrics['relevant_retrieved']} relevant pairs in #{draft_metrics['retrieved']} results.",
    "These measurements #{draft_metrics['precision'] > original_metrics['precision'] ? 'show higher' : 'do not show higher'} strict precision for the structured drafts with this matcher.", ""])
  lines.concat(["", "## Change from baseline", "",
    "Percentage-point changes, not relative percentage improvements. A result may improve recall while reducing precision.", "",
    "| Variant | Strict precision change | Recall change | Additional relevant pairs |", "| --- | --- | --- | --- |"])
  baseline = result["summary"].fetch("baseline")
  %w[structured augmented].each do |variant|
    m = result["summary"].fetch(variant)
    lines << format("| %s | %+.1f pp | %+.1f pp | %+d |", variant,
      (m["precision"] - baseline["precision"]) * 100,
      (m["recall"] - baseline["recall"]) * 100,
      m["relevant_retrieved"] - baseline["relevant_retrieved"])
  end
  lines.concat(["", "## Per-request results", "",
    "Strict precision excludes partial relevance. Precision@5 divides by the returned shortlist size when fewer than five results exist.", "",
    "| Request | Variant | Retrieved | Relevant | Partial | Strict precision | Recall | Precision@5 |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |"])
  changes = 0
  result["requests"].each do |request|
    request["variants"].each do |variant, run|
      m = run["metrics"]
      lines << "| #{request['id']} | #{variant} | #{m['retrieved']} | #{m['relevant_retrieved']} | #{m['partial_retrieved']} | #{pct(m['precision'])} | #{pct(m['recall'])} | #{pct(m['precision_at_5'])} |"
    end
  end
  lines.concat(["", "## Unsupported-request controls", "",
    "These requests have no fully relevant record. Every returned record is a strict false positive, including adjacent partial matches. Recall is N/A.", "",
    "| Request | Baseline false positives | Structured false positives | Augmented false positives |",
    "| --- | --- | --- | --- |"])
  result["requests"].select { |request| request["relevant"].empty? }.each do |request|
    counts = VARIANTS.map { |variant| request["variants"][variant]["metrics"]["false_positives"] }
    lines << "| #{request['id']}: #{md(request['request'])} | #{counts.join(' | ')} |"
  end
  lines.concat(["", "## Relevant-match gains and losses", "",
    "Compared with the baseline, by source-record identity. Matched fields for each gain/loss are available in results.json.", "",
    "| Request | Variant | Newly retrieved relevant records | Lost relevant records |",
    "| --- | --- | --- | --- |"])
  result["requests"].each do |request|
    original = request["variants"]["baseline"]["ranking"].select { |hit| hit["label"] == "relevant" }.map { |hit| hit["id"] }
    %w[structured augmented].each do |variant|
      current = request["variants"][variant]["ranking"].select { |hit| hit["label"] == "relevant" }.map { |hit| hit["id"] }
      gains, losses = current - original, original - current
      next if gains.empty? && losses.empty?
      changes += 1
      lines << "| #{request['id']} | #{variant} | #{gains.empty? ? 'none' : gains.join(', ')} | #{losses.empty? ? 'none' : losses.join(', ')} |"
    end
  end
  lines << "\nNo relevant-match gains or losses occurred." if changes.zero?
  lines.concat(["", "## Added or removed non-relevant results", "",
    "Partial matches are included here because they do not satisfy the full request. This exposes precision changes even when recall is unchanged.", ""])
  result["requests"].each do |request|
    original = request["variants"]["baseline"]["ranking"].map { |hit| hit["id"] }
    %w[structured augmented].each do |variant|
      ranking = request["variants"][variant]["ranking"]
      current = ranking.map { |hit| hit["id"] }
      added = ranking.select { |hit| !original.include?(hit["id"]) && hit["label"] != "relevant" }
      removed = request["variants"]["baseline"]["ranking"].select { |hit| !current.include?(hit["id"]) && hit["label"] != "relevant" }
      added.each do |hit|
        fields = hit["matched_terms"].map { |term, keys| "#{term}: #{keys.join(', ')}" }.join("; ")
        lines << "- #{request['id']} / #{variant} added `#{hit['id']}` (#{hit['label']}); matching fields: #{fields}."
      end
      removed.each { |hit| lines << "- #{request['id']} / #{variant} removed `#{hit['id']}` (#{hit['label']})." }
    end
  end
  lines.concat(["", "## Rankings and evidence", ""])
  result["requests"].each do |request|
    lines.concat(["### #{request['id']}: #{request['request']}", "",
      "**Criterion:** #{request['criterion']}", "", "**Source evidence:** #{request['evidence']}", ""])
    request["variants"].each do |variant, run|
      lines << "**#{variant}:**"
      if run["ranking"].empty?
        lines << "No matches."
      else
        run["ranking"].each_with_index do |hit, i|
          lines << "#{i + 1}. `#{hit['id']}` — #{hit['label']}; score #{hit['score']}; terms: #{hit['matched_terms'].keys.join(', ')}."
        end
      end
      lines << ""
    end
  end
  lines.concat(["## Findings and limitations", "",
    "- Structured labels, ports, and curated use cases make behaviors explicit, but these numbers do not establish that a structured representation is inherently more accurate. Compare precision and recall rather than claiming improvement from additional matches alone.",
    "- Augmented matching is an OR-search over a superset of baseline fields, so recall cannot fall. Added inferred wording can introduce false positives; structured-only can lose original wording.",
    "- Unsupported-request controls expose missing resource, language, and execution constraints. Keyword presence alone does not establish suitability; negation and multi-condition requests need constraint-aware handling.",
    "- Types are proposed representations, not inspected runtime contracts. This matcher only searches type text and does not demonstrate type compatibility, interoperability, or composition.",
    "- These are 16 fixture records, including duplicate identities, revisions, fictional capabilities, invalid manifests, and a deprecated bundle. Functional relevance is not deployability or approval for reuse.",
    "- Requests and judgments were authored after the drafts by one reviewer, using source metadata only. No blind review, held-out queries, significance estimate, or runtime validation supports generalization.",
    "- The A2A-style/free-text comparison files and an OASF implementation are not separate experimental arms here. This is original metadata versus custom ability drafts.",
    "", "## Provisional recommendation", "",
    "Retain original metadata alongside structured abilities and provenance. Use canonical abilities to shortlist, then check resource scope, language, execution behavior, lifecycle, and verified input/output contracts before recommending reuse. Treat missing or unverified details as unresolved, not as support for a requested feature.", ""])
  lines.join("\n")
end

needs_path = EXPERIMENT.join("needs.yaml")
needs = read_yaml(needs_path).fetch("needs")
raise "Expected 16 requests" unless needs.length == 16
raise "Duplicate request IDs" unless needs.map { |need| need.fetch("id") }.uniq.length == needs.length
draft_paths = ROOT.join("ability-descriptions").glob("*.ability.yaml").sort
raise "Expected 16 drafts" unless draft_paths.length == 16
fingerprints = {}
[needs_path, EXPERIMENT.join("run.rb"), EXPERIMENT.join("README.md")].each do |path|
  fingerprints[path.relative_path_from(ROOT).to_s] = Digest::SHA256.file(path).hexdigest
end
items = draft_paths.map do |draft_path|
  draft = read_yaml(draft_path)
  source_file = draft.fetch("source_file")
  source_path = ROOT.join(source_file)
  raise "Source outside examples: #{source_file}" unless source_path.cleanpath.to_s.start_with?(ROOT.join("examples").to_s + "/")
  metadata = read_yaml(source_path)
  original = baseline_fields(metadata)
  structured = structured_fields(draft)
  [source_path, draft_path].each { |path| fingerprints[path.relative_path_from(ROOT).to_s] = Digest::SHA256.file(path).hexdigest }
  {
    "id" => draft_path.basename.to_s.sub(/\.ability\.yaml\z/, ""),
    "name" => metadata.fetch("name"), "source_file" => source_file,
    "draft_file" => draft_path.relative_path_from(ROOT).to_s,
    "fields" => { "baseline" => original, "structured" => structured, "augmented" => original.merge(structured) }
  }
end
expected = ROOT.join("examples").glob("**/*.capability.yaml").map { |path| path.relative_path_from(ROOT).to_s }.sort
raise "Source coverage mismatch" unless items.map { |item| item["source_file"] }.sort == expected
ids = items.map { |item| item["id"] }
needs.each do |need|
  raise "Missing evidence or criterion" unless %w[request criterion evidence].all? { |key| need[key].is_a?(String) && !need[key].empty? }
  terms = need.fetch("terms")
  raise "Invalid terms" unless terms.is_a?(Array) && !terms.empty? && terms.all? { |term| term.is_a?(String) && !normalize(term).empty? }
  raise "Duplicate normalized terms" unless terms.map { |term| normalize(term) }.uniq.length == terms.length
  relevant, partial = need.fetch("relevant"), need.fetch("partial")
  raise "Invalid judgments" unless [relevant, partial].all? { |list| list.is_a?(Array) && list.uniq == list && (list - ids).empty? } && (relevant & partial).empty?
end
requests = needs.map do |need|
  variants = VARIANTS.map do |variant|
    ranked = retrieve(items, need, variant)
    [variant, { "metrics" => metrics(ranked, need["relevant"].length), "ranking" => ranked }]
  end.to_h
  need.merge("variants" => variants)
end
summary = VARIANTS.map do |variant|
  measures = requests.map { |request| request["variants"][variant]["metrics"] }
  ranked = requests.flat_map { |request| request["variants"][variant]["ranking"] }
  aggregate = metrics(ranked, needs.sum { |need| need["relevant"].length })
  aggregate.delete("precision_at_5")
  aggregate["macro_precision"] = mean(measures.map { |m| m["precision"] })
  aggregate["macro_recall"] = mean(measures.map { |m| m["recall"] })
  [variant, aggregate]
end.to_h
result = {
  "protocol" => "local-structured-matching-v1",
  "baseline_status" => "new local baseline; no historical Phase 0 run",
  "input_sha256" => fingerprints.sort.to_h,
  "candidate_count" => items.length,
  "candidates" => items.map { |item| item.reject { |key, _| key == "fields" } },
  "summary" => summary, "requests" => requests
}
File.write(EXPERIMENT.join("results.json"), JSON.pretty_generate(result) + "\n")
File.write(EXPERIMENT.join("results.md"), report(result))
puts "Compared #{items.length} records across #{needs.length} requests."
summary.each { |variant, m| puts "#{variant}: precision #{pct(m['precision'])}; recall #{pct(m['recall'])}; retrieved #{m['retrieved']}" }
